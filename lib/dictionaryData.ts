export type DanishPartOfSpeech =
  | "noun"
  | "verb"
  | "adjective"
  | "adverb"
  | "pronoun"
  | "preposition"
  | "conjunction"
  | "determiner"
  | "number"
  | "interjection"
  | "proper noun"
  | "noun / verb";

export interface DictionaryEntry {
  headword: string;
  english: string;
  partOfSpeech: DanishPartOfSpeech;
  gender?: "en" | "et";
  form?: string;
  note?: string;
  aliases?: readonly string[];
}

export interface DictionaryLookup {
  entry: DictionaryEntry;
  alternatives: readonly DictionaryEntry[];
  selectedForm: string;
  normalized: string;
}

const noun = (
  headword: string,
  english: string,
  gender: "en" | "et",
  form: string,
  aliases: readonly string[] = [],
  note?: string,
): DictionaryEntry => ({ headword, english, partOfSpeech: "noun", gender, form, aliases, note });

const verb = (
  headword: string,
  english: string,
  form: string,
  aliases: readonly string[] = [],
  note?: string,
): DictionaryEntry => ({ headword, english, partOfSpeech: "verb", form, aliases, note });

const adjective = (
  headword: string,
  english: string,
  form: string,
  aliases: readonly string[] = [],
  note?: string,
): DictionaryEntry => ({ headword, english, partOfSpeech: "adjective", form, aliases, note });

const word = (
  headword: string,
  english: string,
  partOfSpeech: Exclude<DanishPartOfSpeech, "noun" | "verb" | "adjective">,
  note: string,
  aliases: readonly string[] = [],
): DictionaryEntry => ({ headword, english, partOfSpeech, note, aliases });

