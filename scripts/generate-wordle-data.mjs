import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import nspell from "nspell";

const [, , affixPath, dictionaryPath, frequencyPath, outputPath = "lib/wordleData.ts"] = process.argv;

if (!affixPath || !dictionaryPath || !frequencyPath) {
  throw new Error("Usage: node scripts/generate-wordle-data.mjs <da_DK.aff> <da_DK.dic> <da_50k.txt> [output]");
}

const fiveDanishLetters = /^[a-zæøå]{5}$/u;
const answerDenyList = new Set([
  "bolle", "bøsse", "fisse", "idiot", "luder", "narko", "penis", "pisse",
  "green", "right", "satan", "sexet", "skide", "skrid", "snøft", "sprut", "times", "tisse", "vædde",
]);

function dictionaryHeadword(line) {
  const lexicalPart = line.split(/[\t ]/, 1)[0] ?? "";
  return lexicalPart.split("/", 1)[0] ?? "";
}

const dictionaryLines = fs.readFileSync(dictionaryPath, "utf8").split(/\r?\n/u).slice(1);
const spell = nspell(fs.readFileSync(affixPath), fs.readFileSync(dictionaryPath));
const allDictionaryHeadwords = new Set(dictionaryLines.map(dictionaryHeadword).filter(Boolean));
const lowercaseDictionaryWords = new Set(
  [...allDictionaryHeadwords].filter((word) => fiveDanishLetters.test(word)),
);

const frequencyRows = fs.readFileSync(frequencyPath, "utf8")
  .split(/\r?\n/u)
  .map((line) => line.match(/^([a-zæøå]{5})\s+(\d+)$/u))
  .filter(Boolean)
  .map((match) => ({ word: match[1], count: Number(match[2]) }));

const frequencyRank = new Map();
for (const row of frequencyRows) {
  if (!frequencyRank.has(row.word)) frequencyRank.set(row.word, frequencyRank.size);
}

const answerCandidates = frequencyRows
  .map((row) => row.word)
  .filter((word, index, words) => words.indexOf(word) === index)
  .filter((word) => lowercaseDictionaryWords.has(word))
  .filter((word) => !allDictionaryHeadwords.has(word[0].toLocaleUpperCase("da-DK") + word.slice(1)))
  .filter((word) => !answerDenyList.has(word));

const answers = answerCandidates.slice(0, 500);
if (answers.length !== 500) throw new Error(`Expected 500 answer words, found ${answers.length}`);

const validFrequencyForms = [...frequencyRank.keys()].filter((word) => spell.correct(word));
const guessSet = new Set([...lowercaseDictionaryWords, ...validFrequencyForms, ...answers]);
const guesses = [...guessSet].sort((left, right) => {
  const leftRank = frequencyRank.get(left) ?? Number.MAX_SAFE_INTEGER;
  const rightRank = frequencyRank.get(right) ?? Number.MAX_SAFE_INTEGER;
  return leftRank - rightRank || left.localeCompare(right, "da-DK");
});

if (guesses.length < 5_000 || guesses.length > 10_000) {
  throw new Error(`Expected 5,000–10,000 guess words, found ${guesses.length}`);
}

const output = `// Generated by scripts/generate-wordle-data.mjs. Do not edit by hand.\n` +
`// Sources and licenses: WORDLE_SOURCES.md\n\n` +
`export const WORDLE_DATA_META = {\n` +
`  answerCount: ${answers.length},\n` +
`  guessCount: ${guesses.length},\n` +
`  wordLength: 5,\n` +
`  dictionaryVersion: \"Stavekontrolden 2.9.109\",\n` +
`  frequencySnapshot: \"FrequencyWords 525f9b560de45753a5ea01069454e72e9aa541c6\",\n` +
`} as const;\n\n` +
`const ANSWER_TEXT = ${JSON.stringify(answers.join("\n"))};\n` +
`const GUESS_TEXT = ${JSON.stringify(guesses.join("\n"))};\n\n` +
`export const WORDLE_ANSWERS = ANSWER_TEXT.split("\\n");\n` +
`export const WORDLE_GUESSES = GUESS_TEXT.split("\\n");\n`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output, "utf8");
console.log(`Generated ${answers.length} answers and ${guesses.length} accepted guesses in ${outputPath}`);
